#!/usr/bin/env python3
"""Regenerate the native Codex payload from the canonical Claude distribution.

INSTALL, AGENTS.md and its local example remain native Codex entrypoints.
Run --check in CI; generation never edits consuming projects.
"""
from pathlib import Path
import json
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
CHECK = sys.argv[1:] == ['--check']
if sys.argv[1:] not in ([], ['--check']):
    sys.exit('usage: gen-codex-distribution.py [--check]')


def native(text):
    text = text.replace('`CLAUDE.md`（codex では `AGENTS.md`）', '`AGENTS.md`')
    text = text.replace('CLAUDE.local.md', 'AGENTS.local.md')
    text = text.replace("('.claude', 'agents')", "('.codex', 'agents')").replace("('.claude', 'skills')", "('.agents', 'skills')")
    text = text.replace("and p.suffix == '.md'", "and p.suffix in ('.md', '.toml')")
    text = text.replace('CLAUDE.md', 'AGENTS.md').replace('.claude/skills', '.agents/skills')
    text = re.sub(r'\.claude/agents/([^`\s"\']+)\.md', r'.codex/agents/\1.toml', text)
    text = text.replace('claude/INSTALL.md', 'codex/INSTALL.md').replace('claude/lock-map.tsv', 'codex/lock-map.tsv')
    text = text.replace('tmp/pdh/claude/', 'tmp/pdh/codex/')
    text = text.replace('/blob/main/claude/', '/blob/main/codex/')
    text = text.replace('frontmatter を除いた本文', 'developer_instructions の本文')
    text = text.replace('frontmatter を除く', 'developer_instructions を読む')
    text = text.replace('bash scripts/gen-agents-md.sh`・`bash scripts/gen-codex-agents.sh', 'project の規則が指定する生成コマンド')
    text = text.replace("{ awk 'NR==1 && /^---$/ {fm=1; next} fm && /^---$/ {fm=0; next} !fm' \".codex/agents/$role.toml\"; cat \"$taskfile\"; } > \"$promptfile\"",
                        "{ python3 -c 'import sys,tomllib; print(tomllib.load(open(sys.argv[1], \"rb\"))[\"developer_instructions\"])' \".codex/agents/$role.toml\"; cat \"$taskfile\"; } > \"$promptfile\"")
    text = text.replace("awk 'NR == 1 && $0 == \"---\" {front=1; next} front && $0 == \"---\" {front=0; next} !front {print}' > \"$run_dir/reviewer.md\"",
                        "python3 -c 'import sys,tomllib; print(tomllib.loads(sys.stdin.read())[\"developer_instructions\"])' > \"$run_dir/reviewer.md\"")
    text = text.replace('本文から frontmatter を除いて', 'developer_instructions の本文を')
    return text


outputs = {}
for file in (ROOT/'claude/skills').rglob('*'):
    if file.is_file():
        rel = file.relative_to(ROOT/'claude')
        if file.suffix in ('.md', '.sh', '.py'):
            outputs[ROOT/'codex'/rel] = native(file.read_text()).encode()
        else:
            outputs[ROOT/'codex'/rel] = file.read_bytes()
# Shared portable scripts are regenerated too; native entrypoints stay hand owned.
for file in (ROOT/'claude/templates').rglob('*'):
    rel = file.relative_to(ROOT/'claude/templates')
    if not file.is_file() or rel.parts[0] == 'agents' or file.name in ('CLAUDE.md','AGENTS.md','CLAUDE.local.md.example','gen-agents-md.sh','gen-codex-agents.sh','settings.json'):
        continue
    if file.name == 'hooks.json':
        outputs[ROOT/'codex/templates'/rel] = file.read_bytes()
    else:
        text = file.read_text().replace('/XXXXXXX/claude/', '/XXXXXXX/codex/')
        outputs[ROOT/'codex/templates'/rel] = native(text).encode()
for file in (ROOT/'claude/templates/agents/claude').glob('pdh-*.md'):
    _, fm, body = file.read_text().split('---',2)
    fields = dict(line.split(':',1) for line in fm.strip().splitlines() if ':' in line)
    text = '# Generated by scripts/gen-codex-distribution.py; edit the canonical Claude agent.\n'
    text += 'name = '+json.dumps(fields['name'].strip(),ensure_ascii=False)+'\n'
    text += 'description = '+json.dumps(fields['description'].strip(),ensure_ascii=False)+'\n'
    text += 'developer_instructions = '+json.dumps(native(body.lstrip('\n')),ensure_ascii=False)+'\n'
    outputs[ROOT/'codex/templates/agents/codex'/f'{file.stem}.toml'] = text.encode()
# Match required paths to the actual standalone installation.
p=ROOT/'codex/templates/checks/required-pdh-files.check'
if p in outputs:
    text=outputs[p].decode()
    line=next(x for x in text.splitlines() if x.startswith('required_paths='))
    paths=line.partition('=')[2].split(',')
    paths=list(dict.fromkeys(x for x in paths if not x.startswith('.claude/')))
    text=text.replace(line,'required_paths='+','.join(paths))
    outputs[p]=text.encode()
expected=set(outputs)
managed=[ROOT/'codex/skills',ROOT/'codex/templates/agents/codex']
stale=[]
for directory in managed:
    for file in directory.rglob('*'):
        if (file.is_file() or file.is_symlink()) and file not in expected:stale.append(file)
errors=[]
for file in stale:
    if CHECK: errors.append(str(file.relative_to(ROOT))+' is obsolete')
    elif file.is_symlink() or file.is_file():file.unlink()
if not CHECK:
    # Replace old symlink trees before writing any payload.
    shutil.rmtree(ROOT/'codex/skills')
for path,data in outputs.items():
    if CHECK:
        if not path.is_file() or path.is_symlink() or path.read_bytes()!=data: errors.append(str(path.relative_to(ROOT)))
    else:
        path.parent.mkdir(parents=True,exist_ok=True)
        if path.is_symlink():path.unlink()
        path.write_bytes(data)
        if path.suffix=='.sh':path.chmod(0o755)
if errors:
    sys.exit('Codex distribution drift:\n'+'\n'.join(errors))
print('Codex distribution: '+('checked' if CHECK else 'generated')+f' {len(outputs)} files')
